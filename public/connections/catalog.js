function normalize(value) {
  return String(value ?? '').normalize('NFD').replace(/\p{M}/gu, '').toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}

const categoryLabels = new Map(CATEGORIES.map(({ id, label }) => [id, label]));
const searchableText = new Map(CONNECTIONS.map((entry) => [entry.id, normalize([
  entry.name, entry.company, ...entry.aliases, entry.description,
  ...entry.categoryIds.map((id) => categoryLabels.get(id)),
].join(' '))]));

/** Pure catalog filtering. `available` means not simulated-connected, not vendor availability. */
export function searchConnections({
  query = '', category = 'all', company = 'all', difficulty = 'all', connectedIds = null, view = 'all',
} = {}) {
  const tokens = normalize(query).split(' ').filter(Boolean);
  const companyFilter = normalize(company);
  const categoryFilter = normalize(category);
  const difficultyFilter = normalize(difficulty);
  const viewFilter = normalize(view);
  const connected = new Set(connectedIds ?? []);
  return CONNECTIONS.filter((entry) => {
    if (categoryFilter !== 'all' && !entry.categoryIds.includes(categoryFilter)) return false;
    if (companyFilter !== 'all' && normalize(entry.company) !== companyFilter) return false;
    if (difficultyFilter !== 'all' && entry.difficulty !== difficultyFilter) return false;
    if (viewFilter === 'connected' && !connected.has(entry.id)) return false;
    if (['available', 'unconnected', 'disconnected'].includes(viewFilter) && connected.has(entry.id)) return false;
    return tokens.every((token) => searchableText.get(entry.id).includes(token));
  });
}
